impl Lockfile {
    pub fn load(path: &Path) -> Result<Lockfile> {
        let text = std::fs::read_to_string(path)
            .map_err(|e| Error::Lockfile(format!("cannot read {}: {e}", path.display())))?;
        Lockfile::from_str(&text)
    }

    pub fn from_str(text: &str) -> Result<Lockfile> {
        // the header is a TOML comment, so the text parses as it is
        let lf: Lockfile =
            toml::from_str(text).map_err(|e| Error::Lockfile(format!("invalid harness.lock: {e}")))?;
        if lf.lock_version != LOCK_VERSION {
            return Err(Error::Lockfile(format!(
                "unsupported lock-version {} (this build supports {})",
                lf.lock_version, LOCK_VERSION
            )));
        }
        lf.validate()?;
        Ok(lf)
    }

    /// Reject names and values that become paths or command-line words and could reach
    /// outside where they belong. A lock can come from someone else's repository (`hlock
    /// pull`), so every consumer gets this check through `load` and `from_str`.
    pub fn validate(&self) -> Result<()> {
        use crate::fsutil::{plain_name, plain_token, safe_rel};
        let name = |what: &str, s: &str| -> Result<()> {
            if plain_name(s) { Ok(()) } else { Err(Error::Lockfile(format!("{what} {s:?} must be a plain name (no '/', '\\', or '..')"))) }
        };
        let rel = |what: &str, s: &str| -> Result<()> {
            if safe_rel(s) { Ok(()) } else { Err(Error::Lockfile(format!("{what} {s:?} must be a relative path inside the project (no leading '/', no '..')"))) }
        };
        let token = |what: &str, s: &str| -> Result<()> {
            if plain_token(s) {
                Ok(())
            } else {
                Err(Error::Lockfile(format!("{what} {s:?} has characters that aren't allowed (letters, digits and ._:/@+- only, not starting with '-')")))
            }
        };
        if !self.harness.name.is_empty() {
            name("[harness] name", &self.harness.name)?;
        }
        if let Some(v) = &self.harness.version {
            token("[harness] version", v)?;
        }
        // a declared dependency's commit and tags reach `git` as arguments
        let dep = |what: &str, d: &Declared| -> Result<()> {
            for (k, v) in [("commit", &d.commit), ("resolved-tag", &d.resolved_tag), ("resolved-ref", &d.resolved_ref)] {
                if let Some(v) = v {
                    token(&format!("{what} {k}"), v)?;
                }
            }
            if let Some(n) = &d.declared_as {
                name(&format!("{what} declared-as"), n)?;
            }
            if let Some(c) = d.constraint.as_deref().filter(|c| c.chars().any(char::is_control)) {
                return Err(Error::Lockfile(format!("{what} constraint {c:?} has control characters")));
            }
            Ok(())
        };
        for s in &self.skill {
            name("[[skill]] name", &s.name)?;
            if let Some(v) = &s.vendored {
                rel(&format!("[[skill]] {} vendored", s.name), v)?;
            }
            dep(&format!("[[skill]] {}", s.name), &s.dep)?;
        }
        for i in &self.instructions {
            if let Some(v) = &i.vendored {
                rel(&format!("[[instructions]] {} vendored", i.name), v)?;
            }
            dep(&format!("[[instructions]] {}", i.name), &i.dep)?;
        }
        for p in &self.package {
            name("[[package]] name", &p.name)?;
            dep(&format!("[[package]] {}", p.name), &p.dep)?;
        }
        for t in &self.tool {
            if let Some(v) = &t.version {
                token(&format!("[[tool]] {} version", t.name), v)?;
            }
            dep(&format!("[[tool]] {}", t.name), &t.dep)?;
        }
        for c in &self.config {
            if let Some(v) = &c.vendored {
                rel(&format!("[[config]] {} vendored", c.id), v)?;
            }
        }
        for n in &self.native {
            if let Some(v) = &n.version {
                token(&format!("[[native]] {} version", n.name), v)?;
            }
            dep(&format!("[[native]] {}", n.name), &n.dep)?;
        }
        for r in &self.runtime {
            token("[[runtime]] name", &r.name)?;
            if let Some(v) = &r.version {
                token(&format!("[[runtime]] {} version", r.name), v)?;
            }
            for m in &r.model {
                token(&format!("[[runtime]] {} model id", r.name), &m.id)?;
                if let Some(src) = &m.source {
                    token(&format!("[[runtime]] {} model {} source", r.name, m.id), src)?;
                }
                if let Some(rev) = &m.revision {
                    token(&format!("[[runtime]] {} model {} revision", r.name, m.id), rev)?;
                }
            }
        }
        for l in &self.llm {
            if let Some(rt) = &l.runtime {
                token(&format!("[[llm]] {} runtime", l.role), rt)?;
            }
        }
        for d in &self.decider {
            if !crate::decide::AGENT_USES.contains(&d.use_.as_str()) {
                return Err(Error::Lockfile(format!("[[decider]] use {:?} isn't one of {}", d.use_, crate::decide::AGENT_USES.join(", "))));
            }
            token(&format!("[[decider]] {} model", d.use_), &d.model)?;
            if let Some(rt) = &d.runtime {
                token(&format!("[[decider]] {} runtime", d.use_), rt)?;
            }
            for w in &d.wiring {
                token(&format!("[[decider]] {} wiring event", d.use_), &w.event)?;
            }
            if let Some(p) = &d.policy {
                rel(&format!("[[decider]] {} policy path", d.use_), &p.path)?;
            }
        }
        Ok(())
    }

    pub fn save(&self, path: &Path) -> Result<()> {
        let body = toml::to_string(&self.without_nulls()).map_err(|e| Error::Lockfile(e.to_string()))?;
        crate::fsutil::write_atomic(path, format!("{HEADER}\n{body}")).map_err(|e| crate::error::at(path, e))
    }

    /// A copy with JSON nulls dropped from the free-form fields (TOML has no null), so a
    /// `null` from the worker or a tune report can't make `save` fail.
    fn without_nulls(&self) -> Lockfile {
        fn map(m: &mut BTreeMap<String, Value>) {
            m.retain(|_, v| !v.is_null());
            m.values_mut().for_each(|v| *v = drop_nulls(v));
        }
        fn opt(o: &mut Option<Value>) {
            match o {
                Some(v) if v.is_null() => *o = None,
                Some(v) => *v = drop_nulls(v),
                None => {}
            }
        }
        let mut l = self.clone();
        map(&mut l.stack);
        l.llm.iter_mut().for_each(|x| map(&mut x.params));
        l.decider.iter_mut().for_each(|d| d.min_probability = drop_nulls(&d.min_probability));
        map(&mut l.policy.sandbox);
        map(&mut l.context.compaction);
        map(&mut l.provenance.search);
        l.native.iter_mut().for_each(|n| opt(&mut n.config));
        opt(&mut l.tune);
        opt(&mut l.localize);
        opt(&mut l.pulled);
        l
    }

    /// True for locks written by `hlock pin` (no manifest, no evidence).
    pub fn is_pin(&self) -> bool {
        self.kind.as_deref() == Some("pin")
    }

    /// Whether this pin captured any user-level setup (`--user` or `--include-user-scope`).
    /// Locks pinned before scopes were recorded captured everything, so they count too.
    pub fn pins_user_scope(&self) -> bool {
        self.provenance.scopes.is_empty() || self.provenance.scopes.iter().any(|s| s == "user")
    }

    pub fn default_path(&self) -> &str {
        LOCKFILE_PATH
    }

    /// Vector of manifest-drift violation strings (empty means clean).
    pub fn check_manifest(&self, live_hash: &str) -> Vec<String> {
        match &self.manifest_hash {
            None => vec!["lock has no manifest-hash".to_string()],
            Some(pinned) => {
                let pinned_hex = pinned.split(':').nth(1).unwrap_or(pinned);
                let live_hex = live_hash.split(':').nth(1).unwrap_or(live_hash);
                if pinned_hex == live_hex {
                    Vec::new()
                } else {
                    vec![format!(
                        "manifest drift: lock pinned {pinned:?}, live {live_hash:?}"
                    )]
                }
            }
        }
    }

    pub fn summary(&self) -> String {
        let model = self.llm.first().map(|l| l.model.as_str()).unwrap_or("?");
        let sr = self.evidence.success_rate.get("mean").unwrap_or(&f64::NAN);
        format!(
            "stack={:?} harness={} llm={} decision={} success-rate={:.2} trials={}",
            self.stack.get("name").and_then(serde_json::Value::as_str).unwrap_or("agent"),
            self.harness.name,
            model,
            self.decision.kind,
            sr,
            self.evidence.trials
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmp(tag: &str) -> std::path::PathBuf {
        let d = std::env::temp_dir().join(format!("hlock-lockfile-{tag}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).unwrap();
        d
    }

    const HEAD: &str = "lock-version = 1\ngenerated-by = \"t\"\ngenerated-at = \"\"\n";

    #[test]
    fn lines_starting_with_hash_inside_strings_survive() {
        let mut l = Lockfile::default();
        l.stack.insert("notes".into(), Value::String("line one\n# not a comment\nline three".into()));
        let d = tmp("hash");
        let p = d.join("harness.lock");
        l.save(&p).unwrap();
        let text = std::fs::read_to_string(&p).unwrap();
        assert!(text.starts_with(HEADER), "the header is written");
        let back = Lockfile::load(&p).unwrap();
        assert_eq!(back.stack["notes"], "line one\n# not a comment\nline three");
        let raw = format!("{HEADER}\n{HEAD}[stack]\nnotes = \"\"\"\na\n# b\nc\"\"\"\n");
        assert_eq!(Lockfile::from_str(&raw).unwrap().stack["notes"], "a\n# b\nc");
        let _ = std::fs::remove_dir_all(&d);
    }

    #[test]
    fn nulls_in_free_form_fields_are_dropped_on_save() {
        let mut l = Lockfile::default();
        l.stack.insert("gone".into(), Value::Null);
        l.tune = Some(serde_json::json!({"data_meta": {"rows": null, "split": [0.7, null]}, "kept": 1}));
        l.pulled = Some(Value::Null);
        l.provenance.search.insert("x".into(), serde_json::json!({"y": null}));
        l.native.push(Native { kind: "pi.package".into(), name: "p".into(), config: Some(serde_json::json!({"a": null})), ..Default::default() });
        let d = tmp("nulls");
        let p = d.join("harness.lock");
        l.save(&p).unwrap();
        let back = Lockfile::load(&p).unwrap();
        assert!(!back.stack.contains_key("gone") && back.pulled.is_none());
        assert_eq!(back.tune.unwrap(), serde_json::json!({"data_meta": {"split": [0.7]}, "kept": 1}));
        assert_eq!(std::fs::read_dir(&d).unwrap().count(), 1, "written by rename; no temp file left");
        let _ = std::fs::remove_dir_all(&d);
    }

    #[test]
    fn names_that_become_paths_or_commands_are_refused() {
        for (body, field) in [
            ("[harness]\nname = \"../../x\"\n", "[harness] name"),
            ("[harness]\nname = \"pi\"\nversion = \"1; curl x|sh\"\n", "[harness] version"),
            ("[[skill]]\nname = \"../evil\"\norigin = \"x\"\n", "[[skill]] name"),
            ("[[skill]]\nname = \"s\"\norigin = \"x\"\nvendored = \"/etc\"\n", "vendored"),
            ("[[instructions]]\nname = \"AGENTS.md\"\nscope = \"project\"\nvendored = \"../../.zshrc\"\n", "vendored"),
            ("[[config]]\nid = \"settings\"\npath = \"x\"\nformat = \"json\"\nrestore = \"whole\"\nvendored = \"a/../../b\"\n", "vendored"),
            ("[[runtime]]\nname = \"ollama\"\nlocation = \"local\"\n[[runtime.model]]\nid = \"--help\"\n", "model id"),
            ("[[decider]]\nuse = \"judge\"\nmodel = \"kev\"\n", "[[decider]] use"),
            ("[[decider]]\nuse = \"stop\"\nmodel = \"kev $(id)\"\n", "[[decider]] stop model"),
            ("[[decider]]\nuse = \"stop\"\nmodel = \"kev\"\n[[decider.wiring]]\nfile = \"settings\"\nevent = \"Stop; rm\"\n", "wiring event"),
            ("[[decider]]\nuse = \"stop\"\nmodel = \"kev\"\n[decider.policy]\npath = \"/etc/passwd\"\ndigest = \"\"\n", "policy path"),
        ] {
            let e = Lockfile::from_str(&format!("{HEAD}{body}")).unwrap_err().to_string();
            assert!(e.contains(field), "{body}: {e}");
        }
        // what real locks hold still loads: instruction names are paths, checked where used
        let ok = format!(
            "{HEAD}[harness]\nname = \"claude-code\"\nversion = \"2.1.0\"\n[[instructions]]\nname = \"~/.claude/CLAUDE.md\"\nscope = \"user\"\n\
             [[runtime]]\nname = \"ollama\"\nlocation = \"local\"\n[[runtime.model]]\nid = \"qwen3:8b\"\nsource = \"ollama:qwen3:8b\"\n\
             [[decider]]\nuse = \"approve\"\nmodel = \"kev:4b\"\nruntime = \"ollama\"\n"
        );
        Lockfile::from_str(&ok).unwrap();
    }
}
